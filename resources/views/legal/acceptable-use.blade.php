<p class="lead text-base text-slate-700 font-medium">
    This Acceptable Use Policy ("AUP") sets out the standards we expect from all users of <strong>EduBridge</strong>, including students, teachers, and visitors. It forms part of our <a href="{{ route('terms') }}">Terms of Service</a>. By using EduBridge you agree to comply with this AUP.
</p>

<h2>1. Purpose</h2>
<p>EduBridge exists to provide a safe, respectful, and effective learning environment for Zimbabwean students and educators. This policy protects users, teachers, and the platform from misuse and ensures that EduBridge remains a trustworthy educational resource for all.</p>

<h2>2. Prohibited Activities</h2>
<p>You must not use EduBridge for any of the following:</p>

<h3>2.1 Illegal activity</h3>
<ul>
    <li>Any activity that violates Zimbabwean law or the laws of your country of residence.</li>
    <li>Harassment, stalking, threatening, or intimidating other users.</li>
    <li>Distributing, promoting, or linking to illegal content.</li>
    <li>Identity fraud, impersonating another person or institution.</li>
    <li>Money laundering or financing of prohibited activities.</li>
</ul>

<h3>2.2 Harmful or offensive content</h3>
<ul>
    <li>Uploading, posting, or transmitting content that is pornographic, sexually explicit, violent, or hateful.</li>
    <li>Content that discriminates against or targets individuals on the basis of race, ethnicity, gender, religion, disability, or sexual orientation.</li>
    <li>Bullying, trolling, or deliberately disrupting lessons, forums, or live sessions.</li>
    <li>Sharing content that promotes self-harm, substance abuse, or dangerous behaviour to minors.</li>
</ul>

<h3>2.3 Academic dishonesty</h3>
<ul>
    <li>Submitting work that is not your own (plagiarism) without proper attribution.</li>
    <li>Sharing quiz answers or examination solutions with other students in a way that undermines assessment integrity.</li>
    <li>Using AI tools (including Chiedza) to complete assessed work that is meant to demonstrate your own understanding, unless explicitly permitted by the assignment instructions.</li>
    <li>Misrepresenting academic qualifications or credentials (this applies especially to teacher accounts).</li>
</ul>

<h3>2.4 Platform abuse</h3>
<ul>
    <li>Attempting to gain unauthorised access to any account, server, database, or system.</li>
    <li>Uploading or transmitting malware, viruses, Trojans, ransomware, or any malicious code.</li>
    <li>Conducting denial-of-service attacks or any form of automated abuse against EduBridge infrastructure.</li>
    <li>Scraping, harvesting, or bulk-downloading content, data, or user information without written permission.</li>
    <li>Using bots, scripts, or automated tools to interact with the platform in a way not sanctioned by EduBridge.</li>
    <li>Exploiting or abusing promotional offers (e.g., creating multiple accounts to claim free access).</li>
    <li>Reselling or sub-licensing your access to another person.</li>
    <li>Circumventing payment systems, account access controls, or digital rights management.</li>
</ul>

<h3>2.5 Privacy violations</h3>
<ul>
    <li>Recording, publishing, or distributing video or audio from live sessions without the explicit consent of all participants.</li>
    <li>Sharing another user's personal information (name, contact details, location) without their consent ("doxxing").</li>
    <li>Collecting or storing personal data about other users through any means.</li>
</ul>

<h3>2.6 Intellectual property infringement</h3>
<ul>
    <li>Uploading content that infringes the copyright, trademarks, or other intellectual property rights of a third party.</li>
    <li>Reproducing or redistributing EduBridge course materials, lesson recordings, or teacher content without authorisation.</li>
    <li>Using ZIMSEC past papers or third-party materials in ways that violate their respective licences.</li>
</ul>

<h2>3. Teacher-Specific Standards</h2>
<p>Teachers on EduBridge are also required to:</p>
<ul>
    <li>Maintain the accuracy, currency, and quality of their teaching materials.</li>
    <li>Disclose any conflict of interest that may affect the objectivity of their content.</li>
    <li>Refrain from using the platform to solicit students for private arrangements that bypass EduBridge (including off-platform payments).</li>
    <li>Follow the EduBridge Teacher Code of Conduct as set out in the Teaching Contract.</li>
    <li>Not upload third-party copyrighted materials (e.g. textbook scans, past papers) without appropriate licencing or fair-use justification.</li>
</ul>

<h2>4. Enforcement and Consequences</h2>
<p>KMG Vital Links (Pvt) Ltd reserves the right to investigate reports of AUP violations and, at its sole discretion, to take the following actions:</p>
<ul>
    <li><strong>Warning:</strong> A formal notice for minor first-time violations.</li>
    <li><strong>Content removal:</strong> Removal of content that violates this policy without prior notice.</li>
    <li><strong>Account suspension:</strong> Temporary restriction of access pending investigation.</li>
    <li><strong>Account termination:</strong> Permanent ban for serious or repeated violations.</li>
    <li><strong>Legal action:</strong> Reporting to Zimbabwean law enforcement authorities or pursuing civil remedies where applicable.</li>
</ul>
<p>No refund will be issued where an account is terminated due to a breach of this AUP.</p>

<h2>5. Reporting Violations</h2>
<p>If you witness or experience behaviour that violates this policy:</p>
<ul>
    <li>Use the <strong>Report</strong> button available on messages, posts, and course content.</li>
    <li>Email <a href="mailto:info@kmgvitallinks.co.uk">info@kmgvitallinks.co.uk</a> with details of the incident.</li>
    <li>For urgent safety concerns (especially involving minors), contact us immediately at <a href="mailto:info@kmgvitallinks.co.uk">info@kmgvitallinks.co.uk</a>.</li>
</ul>
<p>All reports are treated confidentially. We do not disclose the identity of reporters to the reported user.</p>

