<p class="lead text-base text-slate-700 font-medium">
    This policy explains when and how you may request a refund for purchases made on <strong>EduBridge</strong>, operated by <strong>KMG Vital Links (Pvt) Ltd</strong>. We want every student to be satisfied, and we aim to be fair and transparent about our refund terms.
</p>

<h2>1. Free Promotional Access</h2>
<p>During any active promotional period (e.g. the <em>Free for 3 Months</em> enrolment promo), no payment is required and therefore no refund is applicable. Students enrolling under a promotional offer receive a specified period of free access to the course. At the end of the promotional period, access will expire unless a paid subscription is started.</p>
<p>Promotional offers are time-limited and subject to change. We reserve the right to end or modify a promotion at any time with reasonable notice.</p>

<h2>2. Paid Enrolments — 7-Day Refund Window</h2>
<p>If you have paid for course access (monthly, termly, or annual subscription), you are entitled to a full refund if:</p>
<ul>
    <li>You request the refund within <strong>7 days</strong> of your payment date, <strong>and</strong></li>
    <li>You have not completed more than <strong>20% of the course content</strong> (i.e. fewer than 20% of lessons marked as watched).</li>
</ul>
<p>These conditions exist to protect both students and teachers from abuse of the refund system while ensuring genuine dissatisfaction is addressed.</p>

<h2>3. Refunds After the 7-Day Window</h2>
<p>Refunds requested after 7 days from payment are not automatically granted. We may consider exceptional circumstances on a case-by-case basis, including:</p>
<ul>
    <li>Significant and persistent technical failure on our side that prevented reasonable access to the course.</li>
    <li>Accidental duplicate payment (supported by evidence).</li>
    <li>Death or serious medical emergency (documentation required).</li>
</ul>
<p>Discretionary refunds outside the standard window are at the sole judgment of KMG Vital Links management.</p>

<h2>4. Non-Refundable Items</h2>
<p>The following purchases are not eligible for a refund:</p>
<ul>
    <li>Any subscription or enrolment where more than 20% of the course content has been consumed.</li>
    <li>Live session bookings cancelled fewer than 24 hours before the scheduled session start time.</li>
    <li>Purchases made using a coupon code, discount, or promotional offer unless the offer itself states otherwise.</li>
    <li>Partially used subscription periods (i.e. you will retain access for the remainder of the paid period, but we do not pro-rate or refund unused days).</li>
    <li>Platform fees and processing charges levied by payment providers (these are non-recoverable from third parties).</li>
</ul>

<h2>5. Live Session Cancellations</h2>
<ul>
    <li><strong>Cancellation by you (≥ 24 hours notice):</strong> Full credit or refund.</li>
    <li><strong>Cancellation by you (&lt; 24 hours notice):</strong> No refund. The session slot is forfeited.</li>
    <li><strong>Cancellation by the teacher:</strong> Full refund or credit applied to your account within 5 business days.</li>
    <li><strong>Technical failure on our side:</strong> Full refund or rescheduled session at your option.</li>
</ul>

<h2>6. Currency and Processing</h2>
<p>Refunds are processed in the original payment currency and via the original payment method where possible:</p>
<ul>
    <li><strong>Stripe (USD):</strong> Refunds typically appear within 5–10 business days.</li>
    <li><strong>PayFast (USD/ZAR):</strong> Refunds typically appear within 3–5 business days.</li>
    <li><strong>Paynow / EcoCash (ZWG):</strong> Refunds are processed as mobile money reversals within 3–7 business days, subject to provider availability.</li>
    <li><strong>InnBucks (USD):</strong> Refunds processed within 3–5 business days.</li>
</ul>
<p>Currency fluctuations between payment and refund dates are outside our control. Refunds will be made for the original amount paid; exchange-rate differences are not compensated.</p>

<h2>7. How to Request a Refund</h2>
<p>To initiate a refund request:</p>
<ol>
    <li>Log in to your EduBridge account.</li>
    <li>Navigate to <strong>Settings → My Enrolments</strong> and locate the relevant course.</li>
    <li>Click <strong>Request Refund</strong> and provide a brief reason.</li>
    <li>Alternatively, email <a href="mailto:info@kmgvitallinks.co.uk">info@kmgvitallinks.co.uk</a> with your registered email address, the course name, and your payment reference number.</li>
</ol>
<p>We aim to acknowledge all refund requests within 2 business days and to resolve them within 10 business days.</p>

<h2>8. Chargebacks</h2>
<p>If you initiate a chargeback with your bank or payment provider before contacting us, your account may be suspended pending investigation. We encourage you to contact us first — we are committed to resolving legitimate disputes quickly and fairly.</p>

<h2>9. Changes to This Policy</h2>
<p>KMG Vital Links reserves the right to update this Refund Policy at any time. Changes will be effective from the date of publication on this page. Any purchases made before a policy change will be governed by the policy in effect at the time of purchase.</p>

